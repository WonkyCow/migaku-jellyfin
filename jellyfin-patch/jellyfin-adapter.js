/*
 * Jellyfin adapter for Migaku (personal-use POC). Original code, written for this project.
 *
 * This is NOT a standalone script: patch.py inserts it into the page-world bundle (*.umd.cjs),
 * inside the closure that defines Migaku's adapter base class and language normaliser.
 * patch.py locates those minified identifiers by pattern and substitutes the placeholders
 * __BASE__, __LANGNORM__ and __JF_HOST_RE__ (a regex source matching your configured hosts).
 */
const JF_HOST_RE = /^(?:__JF_HOST_RE__)$/i;
const jfMatch = () => JF_HOST_RE.test(location.hostname) && /\/web\//.test(location.pathname);

class JellyfinAdapter extends __BASE__ {
  videoElementSelector = "video.htmlvideoplayer";
  // Sidebar: stand-in is appended to <body>; the player container is shrunk to make room.
  standInSiblingSelector = ".videoPlayerContainer";
  standInContainerSelector = "body";
  playerUiOverlayContainerSelector = ".videoPlayerContainer";

  ready = false;
  item = null;
  mediaSource = null;
  audioIndex = null;
  tracks = [];
  srcKey = null;
  loading = false;
  pollId = null;
  lastAudioCheck = 0;
  vttCache = new Map();
  widthObserver = null;
  styleId = "migaku-jf-style";
  uiStyleId = "migaku-jf-ui-hidden";

  constructor() {
    super();
    this.pollId = setInterval(() => {
      this.poll().catch((e) => console.error("[Migaku-JF] poll failed", e));
    }, 700);
  }

  // ---- Jellyfin API helpers -------------------------------------------------
  api() {
    return window.ApiClient;
  }

  iso1(code) {
    const map = {
      jpn: "ja", jap: "ja", eng: "en", spa: "es", fre: "fr", fra: "fr", ger: "de", deu: "de",
      ita: "it", kor: "ko", por: "pt", zho: "zh", chi: "zh", cmn: "zh", vie: "vi", yue: "yue",
    };
    const c = (code || "").toLowerCase();
    return map[c] || c;
  }

  async fetchNowPlaying() {
    const c = this.api();
    if (!c) return null;
    const sessions = await c.getJSON(c.getUrl("Sessions", { DeviceId: c.deviceId() }));
    const s = (sessions || []).find((x) => x.NowPlayingItem);
    if (!s) return null;
    const ps = s.PlayState || {};
    const full = await c.getItem(c.getCurrentUserId(), s.NowPlayingItem.Id);
    const sources = full.MediaSources || [];
    const ms = sources.find((m) => m.Id === ps.MediaSourceId) || sources[0];
    if (!ms) return null;
    return { item: full, mediaSource: ms, audioIndex: ps.AudioStreamIndex ?? ms.DefaultAudioStreamIndex ?? null };
  }

  audioLang() {
    const streams = this.mediaSource?.MediaStreams || [];
    const a = streams.find((s) => s.Type === "Audio" && s.Index === this.audioIndex);
    return a ? this.iso1(a.Language) : null;
  }

  buildTracks() {
    const c = this.api();
    const base = c.serverAddress();
    const ms = this.mediaSource;
    const audio = this.audioLang();
    return (ms.MediaStreams || [])
      .filter((s) => s.Type === "Subtitle" && s.IsTextSubtitleStream !== false)
      .map((s) => {
        const raw = this.iso1(s.Language) || "und";
        let lang = raw;
        try {
          lang = __LANGNORM__(raw) || raw;
        } catch (_) {}
        return {
          bestUrl: `${base}/Videos/${this.item.Id}/${ms.Id}/Subtitles/${s.Index}/0/Stream.vtt`,
          id: `jf-${this.item.Id}-${s.Index}`,
          isNative: !!audio && raw === audio,
          isClosedCaptions: !!s.IsHearingImpaired,
          isAutoGenerated: false,
          rawLanguage: raw,
          language: lang,
          languageDescription: s.DisplayTitle || s.Title || raw,
        };
      });
  }

  title() {
    const i = this.item;
    if (!i) return "Unknown title";
    return i.SeriesName ? `${i.SeriesName} - ${i.Name}` : i.Name || "Unknown title";
  }

  // Jellyfin converts ASS to VTT but leaves ASS override codes ({\i1}, {\pos(..)}, \N) in the text.
  cleanAss(text) {
    return text.replace(/\{\\[^}]*\}/g, "").replace(/\\[Nn]/g, "\n").replace(/\\h/g, " ");
  }

  // ---- lifecycle ------------------------------------------------------------
  async poll() {
    const el = document.querySelector(this.videoElementSelector);
    const live = !!el && el.isConnected && el.readyState >= 1 && el.duration > 0;
    if (!live) {
      if (this.ready) this.teardown();
      return;
    }
    if (this.loading) return;
    if (this.ready && this.videoElement === el && this.srcKey === el.currentSrc) {
      await this.refreshAudio();
      return;
    }
    this.loading = true;
    try {
      await this.load(el);
    } finally {
      this.loading = false;
    }
  }

  async refreshAudio() {
    if (Date.now() - this.lastAudioCheck < 3000) return;
    this.lastAudioCheck = Date.now();
    const np = await this.fetchNowPlaying().catch(() => null);
    if (np && np.item.Id === this.item?.Id && np.audioIndex !== this.audioIndex) this.audioIndex = np.audioIndex;
  }

  async load(el) {
    const np = await this.fetchNowPlaying();
    if (!np) return;
    const itemChanged = this.item && this.item.Id !== np.item.Id;
    if (this.ready) {
      this.ready = false;
      this.broadcastVideoReadyState(false);
    }
    this.item = np.item;
    this.mediaSource = np.mediaSource;
    this.audioIndex = np.audioIndex;
    this.tracks = this.buildTracks();
    this.vttCache.clear();
    this.videoElement = el;
    this.videoPlayer = {
      play: () => el.play(),
      pause: () => el.pause(),
      seek: (ms) => {
        el.currentTime = ms / 1000 + 0.001;
      },
    };
    this.srcKey = el.currentSrc;
    this.injectStyle();
    this.monitorVideoElements();
    this.loadPlayer();
    this.watchAudioTrackForChange();
    this.appendSubtitleBrowserStandIn();
    this.ready = true;
    this.broadcastVideoReadyState(true);
    if (itemChanged) this.broadCastVideoDataUpdated();
  }

  teardown() {
    this.ready = false;
    this.srcKey = null;
    this.broadcastVideoReadyState(false);
    clearInterval(this.videoMonitorInterval);
    document.getElementById(this.styleId)?.remove();
    document.getElementById(this.uiStyleId)?.remove();
    this.stopObservingWidth();
    try {
      this.hideSubtitleBrowserStandin();
    } catch (_) {}
  }

  injectStyle() {
    let s = document.getElementById(this.styleId);
    if (!s) {
      s = document.createElement("style");
      s.id = this.styleId;
      document.head.appendChild(s);
    }
    // Hide Jellyfin's own subtitle renderers so only Migaku's overlay shows.
    // Layout fix: Migaku forces the player container to position:relative while the sidebar stand-in
    // is active, which collapses Jellyfin's fixed full-viewport player to the video's aspect height
    // and leaves the OSD at full width underneath the sidebar. Restore fixed full-height and size the
    // OSD to the (Migaku-resized) player width, exposed through --mgk-jf-w.
    const act = "body.-mgk-video-page.-mgk-active";
    s.textContent =
      ".videoSubtitles,.libassjs-canvas-parent{display:none!important}" +
      "video.htmlvideoplayer::cue{background:transparent!important;color:transparent!important;text-shadow:none!important}" +
      `${act} .videoPlayerContainer.-mgk-sub-browser-stand-in-sibling{position:fixed!important;top:0!important;left:0!important;bottom:0!important;height:100%!important}` +
      `${act} #videoOsdPage{right:auto!important;width:var(--mgk-jf-w,100%)!important}` +
      `${act} #videoOsdPage .videoOsdBottom,${act} .skinHeader.osdHeader,${act} .upNextContainer{right:auto!important;width:var(--mgk-jf-w,100%)!important}`;
    this.observeWidth();
  }

  observeWidth() {
    const pc = document.querySelector(this.standInSiblingSelector);
    if (!pc || this.widthObserver) return;
    const apply = () => document.documentElement.style.setProperty("--mgk-jf-w", `${pc.offsetWidth}px`);
    this.widthObserver = new ResizeObserver(apply);
    this.widthObserver.observe(pc);
    apply();
  }

  stopObservingWidth() {
    this.widthObserver?.disconnect();
    this.widthObserver = null;
    document.documentElement.style.removeProperty("--mgk-jf-w");
  }

  // ---- adapter interface ----------------------------------------------------
  async getVideoData() {
    return { title: this.title(), availableSubtitles: [...this.tracks, ...this.localSubtitles], isRecordingBlocked: false };
  }

  async getVideoInfo() {
    return { title: this.title() };
  }

  getMovieIdFromUrl() {
    return this.item?.Id ?? null;
  }

  getCurrentAudioTrack() {
    return { isNative: null, rawLanguage: this.audioLang() };
  }

  async getSubtitle(meta, isTarget) {
    try {
      let text = this.vttCache.get(meta.bestUrl);
      if (text === undefined) {
        text = await this.api().fetch({ url: meta.bestUrl, type: "GET", dataType: "text" });
        text = this.cleanAss(text);
        this.vttCache.set(meta.bestUrl, text);
      }
      if (isTarget) this.addTrackElement(new Blob([text], { type: "text/vtt" }));
      meta.subtitles = this.vttSubtitleToFullSubtitleData(text, meta.language);
      return meta;
    } catch (e) {
      console.error("[Migaku-JF] subtitle fetch failed", e);
      return null;
    }
  }

  awaitVideoToFinishLoading(cb) {
    const el = this.videoElement;
    const start = Date.now();
    const id = setInterval(() => {
      if (!el || (!el.seeking && el.readyState >= 3) || Date.now() - start > 8000) {
        clearInterval(id);
        cb();
      }
    }, 100);
  }

  hideVideoUI() {
    let s = document.getElementById(this.uiStyleId);
    if (!s) {
      s = document.createElement("style");
      s.id = this.uiStyleId;
      document.head.appendChild(s);
    }
    s.textContent =
      "#videoOsdPage .videoOsdBottom,#videoOsdPage .osdHeader,.skinHeader,.upNextContainer,.videoOsdPage{opacity:0!important;pointer-events:none!important}";
  }

  displayVideoUI() {
    const s = document.getElementById(this.uiStyleId);
    if (s) s.textContent = "";
  }
}
